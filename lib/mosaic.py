def _draw_text(canvas, text, x, y, scale=2, color=(1.0, 1.0, 1.0)):
    """Печатает `text` в `canvas` (см. `_FONT`), верхний левый угол — (x, y).

    Символы вне алфавита `_FONT` пропускаются, а не роняют вызов — подпись
    рассчитана на короткие ярлыки вроде "prev"/"curr", а не на произвольный
    текст с кириллицей.
    """
    cx = x
    for ch in text.upper():
        glyph = _FONT.get(ch)
        if glyph is None:
            cx += 6 * scale
            continue
        for row, bits in enumerate(glyph):
            for col, bit in enumerate(bits):
                if bit == "1":
                    yy, xx = y + row * scale, cx + col * scale
                    canvas[yy:yy + scale, xx:xx + scale, :3] = color
                    canvas[yy:yy + scale, xx:xx + scale, 3] = 1.0
        cx += 6 * scale
    return cx


def side_by_side(prev_path, curr_path, out_path, labels=("prev", "curr"),
                 gap=6, bg=0.09, caption_h=14):
    """Два PNG рядом с подписями — «было/стало» без анализа, глазами.

    Изображения кладутся в исходном размере, без масштабирования — ширина
    результата равна сумме исходных ширин плюс `gap`. Каждое выравнивается
    по верхнему краю; если высоты разные, разница остаётся фоном снизу.
    Подписи из `labels` печатаются под каждой половиной минимальным
    встроенным шрифтом (латиница, цифры — см. `_FONT`); для числовой оценки
    разницы, а не взгляда, — `lib/diff.py:perceptual_diff`.
    """
    a, b = load(prev_path), load(curr_path)
    ha, wa, _ = a.shape
    hb, wb, _ = b.shape
    h = max(ha, hb)
    w = wa + gap + wb

    canvas = np.zeros((h + caption_h, w, 4), dtype=np.float32)
    canvas[..., :3] = bg
    canvas[..., 3] = 1.0
    canvas[:ha, :wa] = a
    canvas[:hb, wa + gap:wa + gap + wb] = b

    _draw_text(canvas, labels[0], 4, h + 3, scale=1)
    _draw_text(canvas, labels[1], wa + gap + 4, h + 3, scale=1)

    save(canvas, out_path)
    return out_path
